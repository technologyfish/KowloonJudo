/**
 * 根据出生年份获取可选的年龄组别列表
 * 特例：
 *   大师1组（1987-1996）→ 可选 大师1 或 成人
 *   大师2组（1986及以前）→ 可选 大师2、大师1 或 成人
 *
 * @param {number} birthYear  出生年份
 * @returns {string[]}  可选的年龄组别列表
 */
export function getAvailableAgeGroups(birthYear) {
  if (!birthYear || isNaN(birthYear)) return []

  const year = Number(birthYear)

  // 找到默认组别
  const entry = BIRTH_YEAR_MAP.find(e => year >= e.min && year <= e.max)
  if (!entry) return []

  const defaultGroup = entry.group

  // 特例：大师1可选成人
  if (defaultGroup === '大师1(30岁以上)') {
    return ['大师1(30岁以上)', '成人(18岁以上)']
  }

  // 特例：大师2可选大师1、成人
  if (defaultGroup === '大师2(40岁以上)') {
    return ['大师2(40岁以上)', '大师1(30岁以上)', '成人(18岁以上)']
  }

  // 其他组别只能选默认
  return [defaultGroup]
}

