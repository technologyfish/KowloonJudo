//  带色
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
const CHILDREN_BELTS = ['白带', '灰带', '黄带', '橙带', '绿带']   // 4-15岁
const YOUTH_BELTS    = ['白带', '蓝带', '紫带', '棕带', '黑带']   // 16-17岁
const ADULT_BELTS    = ['白带', '蓝带', '紫带', '棕带', '黑带']   // 18岁以上

/**
 * 根据年龄组别获取可选带色
 * 4-15岁：白灰黄橙绿
 * 16-17岁：白蓝紫棕黑
 * 成人/大师：白蓝紫棕黑
 * @param {string} ageGroup
 * @returns {string[]}
 */
export function getBeltColors(ageGroup) {
  if (!ageGroup) return []
  if (CHILDREN_GROUPS.includes(ageGroup)) {
    return CHILDREN_BELTS
  }
  if (ageGroup === YOUTH_GROUP) {
    return YOUTH_BELTS
  }
  return ADULT_BELTS
}

// 向后兼容：完整带色列表
export const BELT_COLORS = [...new Set([...CHILDREN_BELTS, ...ADULT_BELTS])]

// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
//  查询体重列表
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
function lookupWeights(table, ageGroup, gender) {
  if (!ageGroup) return []

  // 少儿 4-15岁 → 不分性别
  if (CHILDREN_GROUPS.includes(ageGroup)) {
    return table[ageGroup] || []
  }

  // 青年 16-17岁 → 分男女
  if (ageGroup === YOUTH_GROUP) {
    return table[`${YOUTH_GROUP}_${gender || '男'}`] || []
  }

  // 成人/大师 → 共用同一套男女体重表
  if (ADULT_GROUPS.includes(ageGroup)) {
    return table[`成人_${gender || '男'}`] || []
  }

  return []
}

/**
 * 获取 GI 道服组体重列表
 */
export function getGIWeights(ageGroup, gender) {
  return lookupWeights(GI_WEIGHTS, ageGroup, gender)
}

/**
 * 获取 NO-GI 无道服组体重列表
 */
export function getNOGIWeights(ageGroup, gender) {
  return lookupWeights(NOGI_WEIGHTS, ageGroup, gender)
}
